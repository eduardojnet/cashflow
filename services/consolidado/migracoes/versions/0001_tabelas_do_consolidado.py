"""Tabelas do consolidado, geração inicial ativa e privilégios (004-T1).

Revision ID: 0001
Revises:
Create Date: 2026-11-06

Cria as tabelas de design 004 §4, com dono consolidado_migracao, e a geração
inicial ativa, apontada por `controle_projecao` e com checkpoint na posição 0
(FR-007; design 004 §13; INFRA 3.2).

Inbox, contribuição, saldo, marcador, checkpoint e lacuna são por geração
(design 004 §4): o replay da spec 005 republica o mesmo `evento_id`, e cada
geração deduplica o seu (TD-001). A quarentena não é por geração (D-008).

Privilégio mínimo (INFRA 5.11; design 004 §5, §6):
  - consolidado_api só lê o que a consulta usa (FR-004 a FR-007): geração
    ativa, saldo, marcador de inclusão e checkpoint. Não escreve em nada.
  - consolidado_worker lê o controle e escreve só o que a transação do fluxo
    de design 004 §3 usa (004-T3, T4). Inbox, contribuição, marcador e
    quarentena são só de inserção; saldo e checkpoint são atualizados só nas
    colunas de valor; lacuna é removida quando a posição chega (TD-006).
  - consolidado_operacao recebe seus privilégios na migração da spec 005,
    que controla o ciclo de vida das gerações.
"""

from collections.abc import Sequence

from alembic import op

revision: str = "0001"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

TABELAS = [
    "geracao",
    "controle_projecao",
    "inbox",
    "contribuicao",
    "saldo_diario",
    "marcador_inclusao",
    "checkpoint",
    "lacuna",
    "quarentena",
]


def upgrade() -> None:
    # Estados do ciclo de vida de design 005 §3; nesta spec só existe a
    # geração ativa. No máximo uma geração ativa por vez (INFRA 2.3).
    op.execute(
        """
        CREATE TABLE geracao (
            id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            estado    text        NOT NULL
                                  CHECK (estado IN ('construindo', 'ativa',
                                                    'anterior', 'descartada')),
            criada_em timestamptz NOT NULL DEFAULT now()
        )
        """
    )
    op.execute(
        "CREATE UNIQUE INDEX ux_geracao_uma_ativa ON geracao (estado)"
        " WHERE estado = 'ativa'"
    )

    # Linha única com o ponteiro que a API lê em cada consulta (FR-007).
    op.execute(
        """
        CREATE TABLE controle_projecao (
            id               smallint PRIMARY KEY CHECK (id = 1),
            geracao_ativa_id bigint   NOT NULL REFERENCES geracao (id)
        )
        """
    )

    # Deduplicação por evento; o hash separa duplicata idêntica de conflito
    # (TD-001, FR-003).
    op.execute(
        """
        CREATE TABLE inbox (
            geracao_id  bigint      NOT NULL REFERENCES geracao (id),
            evento_id   uuid        NOT NULL,
            hash        text        NOT NULL CHECK (hash <> ''),
            recebido_em timestamptz NOT NULL DEFAULT now(),
            PRIMARY KEY (geracao_id, evento_id)
        )
        """
    )

    # Contribuição única por lançamento (TD-001). Tipo, valor e data com as
    # mesmas regras do livro (002 design §4). A posição do livro não tem
    # lacunas nem repetição (002 TD-002): a unicidade por geração recusa outro
    # lançamento na mesma posição e serve ao avanço do checkpoint (TD-006).
    op.execute(
        """
        CREATE TABLE contribuicao (
            geracao_id      bigint         NOT NULL REFERENCES geracao (id),
            lancamento_id   uuid           NOT NULL,
            posicao         bigint         NOT NULL CHECK (posicao > 0),
            data_lancamento date           NOT NULL,
            tipo            text           NOT NULL
                                           CHECK (tipo IN ('DEBITO', 'CREDITO')),
            valor           numeric(14, 2) NOT NULL CHECK (valor > 0),
            hash            text           NOT NULL CHECK (hash <> ''),
            PRIMARY KEY (geracao_id, lancamento_id),
            UNIQUE (geracao_id, posicao)
        )
        """
    )

    # Saldo materializado por geração e data (TD-004; D-001). Totais sem teto
    # de escala: a soma de muitos valores de numeric(14, 2) passa do teto de
    # um lançamento. O saldo do dia é sempre créditos menos débitos; o
    # acumulado é calculado na consulta (TD-007).
    op.execute(
        """
        CREATE TABLE saldo_diario (
            geracao_id     bigint         NOT NULL REFERENCES geracao (id),
            data           date           NOT NULL,
            total_creditos numeric(20, 2) NOT NULL DEFAULT 0
                                          CHECK (total_creditos >= 0),
            total_debitos  numeric(20, 2) NOT NULL DEFAULT 0
                                          CHECK (total_debitos >= 0),
            saldo_dia      numeric(20, 2) NOT NULL DEFAULT 0,
            PRIMARY KEY (geracao_id, data),
            CHECK (saldo_dia = total_creditos - total_debitos)
        )
        """
    )

    # Sinal de inclusão (FR-006).
    op.execute(
        """
        CREATE TABLE marcador_inclusao (
            geracao_id    bigint      NOT NULL REFERENCES geracao (id),
            lancamento_id uuid        NOT NULL,
            posicao       bigint      NOT NULL CHECK (posicao > 0),
            incluido_em   timestamptz NOT NULL DEFAULT now(),
            PRIMARY KEY (geracao_id, lancamento_id)
        )
        """
    )

    # Maior posição contínua projetada (TD-006); 0 = nada projetado.
    op.execute(
        """
        CREATE TABLE checkpoint (
            geracao_id       bigint      PRIMARY KEY REFERENCES geracao (id),
            posicao_continua bigint      NOT NULL DEFAULT 0
                                         CHECK (posicao_continua >= 0),
            atualizado_em    timestamptz NOT NULL DEFAULT now()
        )
        """
    )

    # Posições ausentes abaixo da maior já projetada (TD-006; INFRA 8.3).
    op.execute(
        """
        CREATE TABLE lacuna (
            geracao_id bigint NOT NULL REFERENCES geracao (id),
            posicao    bigint NOT NULL CHECK (posicao > 0),
            PRIMARY KEY (geracao_id, posicao)
        )
        """
    )

    # Quarentena durável (D-008; INFRA 4.9, 4.10). Mensagem ilegível pode não
    # ter `evento_id`; o payload fica em bytes, como chegou.
    op.execute(
        """
        CREATE TABLE quarentena (
            id            bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            evento_id     uuid,
            motivo        text        NOT NULL CHECK (motivo <> ''),
            payload_bruto bytea       NOT NULL,
            recebido_em   timestamptz NOT NULL DEFAULT now()
        )
        """
    )

    # Geração inicial ativa, controle e checkpoint (design 004 §13).
    op.execute("INSERT INTO geracao (estado) VALUES ('ativa')")
    op.execute(
        "INSERT INTO controle_projecao (id, geracao_ativa_id)"
        " SELECT 1, id FROM geracao WHERE estado = 'ativa'"
    )
    op.execute(
        "INSERT INTO checkpoint (geracao_id)"
        " SELECT geracao_ativa_id FROM controle_projecao WHERE id = 1"
    )

    # Privilégio mínimo (ver docstring). Nada para PUBLIC.
    op.execute(f"REVOKE ALL ON {', '.join(TABELAS)} FROM PUBLIC")

    op.execute(
        "GRANT SELECT ON geracao, controle_projecao, saldo_diario,"
        " marcador_inclusao, checkpoint TO consolidado_api"
    )

    op.execute("GRANT SELECT ON geracao, controle_projecao TO consolidado_worker")
    op.execute(
        "GRANT SELECT, INSERT ON inbox, contribuicao, marcador_inclusao, quarentena"
        " TO consolidado_worker"
    )
    op.execute(
        "GRANT SELECT, INSERT, UPDATE (total_creditos, total_debitos, saldo_dia)"
        " ON saldo_diario TO consolidado_worker"
    )
    op.execute(
        "GRANT SELECT, UPDATE (posicao_continua, atualizado_em)"
        " ON checkpoint TO consolidado_worker"
    )
    op.execute("GRANT SELECT, INSERT, DELETE ON lacuna TO consolidado_worker")


def downgrade() -> None:
    # A projeção é reconstruível a partir do livro (INFRA 2.5), mas o caminho
    # de volta é a troca de geração da spec 005, não apagar o esquema.
    raise NotImplementedError("a migração inicial do consolidado não tem downgrade")
